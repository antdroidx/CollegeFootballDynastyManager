"""Real-device pro foundation checks; only operates on the disposable CI emulator."""
import importlib.util
import time
from pathlib import Path
spec=importlib.util.spec_from_file_location("college_smoke",Path(__file__).with_name("android-ui-smoke.py"))
s=importlib.util.module_from_spec(spec);spec.loader.exec_module(s)
def ready(name,label): return s.wait_for("pro-"+name,lambda r:label in s.texts(r),timeout=180)
def click(name,label):
    root=s.scroll_to_text("pro-"+name,label,max_swipes=20);s.tap(root,label);return root
try:
    home=ready("library","New franchise")
    assert "PRO FOOTBALL" in s.texts(home)
    s.tap(home,"New franchise")
    create=ready("create","Start franchise")
    assert "Boston Sentinels" in s.texts(create)
    s.tap(create,"Start franchise")
    overview=ready("overview","Advance week")
    assert any("Preseason" in (t or "") for t in s.texts(overview))
    click("watch-open","Watch")
    live=ready("watch","Pause watch")
    s.tap(live,"Pause watch")
    time.sleep(2)
    click("replay","Instant replay")
    time.sleep(2)
    s.adb("shell","settings","put","system","accelerometer_rotation","0")
    s.adb("shell","settings","put","system","user_rotation","1")
    time.sleep(2);s.capture("pro-live-landscape")
    s.adb("shell","settings","put","system","user_rotation","0")
    click("finish","Finish game")
    final=ready("final","FINAL · Saved")
    click("return","Return to franchise")
    ready("completed-overview","Box score")
    click("save-exit","Save & exit")
    library=ready("saved-library","Your franchises")
    # Reinstall as an update; the existing franchise must survive.
    apk=next(Path("apk").glob("*-Signed.apk"))
    s.adb("install","-r",str(apk))
    s.adb("shell","monkey","-p","antdroid.profootball.franchise","-c","android.intent.category.LAUNCHER","1")
    library=ready("updated-library","Your franchises")
    slot=next(t for t in s.texts(library) if (t or "").startswith("My franchise · Boston Sentinels"))
    s.tap(library,slot)
    restored=ready("reload","Box score")
    assert any("Final" in (t or "") for t in s.texts(restored))
    click("advance","Advance week")
    confirm=ready("advance-confirm","Advance week?")
    s.tap(confirm,"Advance")
    advanced=s.wait_for("pro-week2",lambda r:any("Week 2" in (t or "") for t in s.texts(r)),timeout=240)
    click("play-open","Play")
    viewer=ready("coach-mode","Next snap")
    click("offense","Choose offense")
    choices=ready("play-choices","Offensive play")
    s.tap(choices,"Cancel")
    click("coach-snap","Next snap")
    time.sleep(2);s.capture("pro-coach-after-snap")
    click("leave-coach","Return to franchise")
    leave=ready("leave-confirm","Leave game?")
    s.tap(leave,"Leave")
    click("exit-coach","Save & exit")
    library=ready("theme-library","Appearance")
    s.tap(library,"Appearance")
    choices=ready("theme-choices","Light")
    s.tap(choices,"Light")
    light=ready("light-library","New franchise")
    s.adb("shell","wm","size","1768x2208")
    s.adb("shell","wm","density","340")
    time.sleep(2);s.capture("pro-fold-light")
    assert s.adb("shell","pidof","antdroid.profootball.franchise").strip()
    print("Pro launch, franchise creation, watch/replay, landscape, saved final, reload, advance and coach mode passed.",flush=True)
finally:
    Path("pro-logcat.txt").write_bytes(s.adb("logcat","-d"))
